import { counter, histogram, gauge } from "./metrics"
import { getLogger } from "./logger"

const log = getLogger("system")

// ── Search Telemetry ──

export const searchLatency = histogram("search_latency_ms", "search", "Latency of search operations in milliseconds")
export const searchCount = counter("search_total", "search", "Total number of search operations")
export const searchErrors = counter("search_errors", "search", "Total number of search failures")
export const searchFilesScanned = histogram("search_files_scanned", "search", "Number of files scanned per search")
export const searchResultsReturned = histogram("search_results_returned", "search", "Number of results returned per search")

export function recordSearch(durationMs: number, filesScanned: number, resultsCount: number, error?: string): void {
  searchCount.inc()
  searchLatency.observe(durationMs)
  searchFilesScanned.observe(filesScanned)
  searchResultsReturned.observe(resultsCount)
  if (error) {
    searchErrors.inc()
    log.warn("search failed", { error, durationMs, metadata: { filesScanned, resultsCount } })
  }
}

