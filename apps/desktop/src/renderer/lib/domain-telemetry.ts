// ── Memory Telemetry ──

export const memoryHeapUsed = gauge("memory_heap_used_mb", "system", "Heap memory used in MB")
export const memoryHeapTotal = gauge("memory_heap_total_mb", "system", "Total heap memory in MB")
export const memoryGrowthRate = gauge("memory_growth_rate_mb_per_hour", "system", "Memory growth rate")

export function sampleMemory(): void {
  const usage = process.memoryUsage?.()
  if (!usage) return
  memoryHeapUsed.set(Math.round(usage.heapUsed / (1024 * 1024)))
  memoryHeapTotal.set(Math.round(usage.heapTotal / (1024 * 1024)))
}

// ── CPU Telemetry ──

export const cpuUser = gauge("cpu_user_percent", "system", "CPU user time percentage")
export const cpuSystem = gauge("cpu_system_percent", "system", "CPU system time percentage")
let lastCpuUsage = process.cpuUsage?.()

export function sampleCpu(): void {
  const current = process.cpuUsage?.()
  if (!current || !lastCpuUsage) {
    lastCpuUsage = current
    return
  }
  const userDelta = current.user - lastCpuUsage.user
  const sysDelta = current.system - lastCpuUsage.system
  const totalDelta = userDelta + sysDelta
  if (totalDelta > 0) {
    cpuUser.set(Math.round((userDelta / totalDelta) * 100))
    cpuSystem.set(Math.round((sysDelta / totalDelta) * 100))
  }
  lastCpuUsage = current
}

// ── Periodic Sampling ──

let samplingInterval: ReturnType<typeof setInterval> | null = null

export function startPeriodicSampling(intervalMs = 5000): void {
  stopPeriodicSampling()
  samplingInterval = setInterval(() => {
    sampleMemory()
    sampleCpu()
  }, intervalMs)
}

export function stopPeriodicSampling(): void {
  if (samplingInterval) {
    clearInterval(samplingInterval)
    samplingInterval = null
  }
}

